import type { Cell, ImsiCheck, ImsiOwners, Interaction, Observation, RawSheet, RawWorkbook, SheetStat, SourceKind, ZMode } from '../types';
import { normalizeNumber, operatorFromPlmn, type PhoneInfo } from '../phone';
import { parseWallClock } from '../time';
import { imeiCore, likelySameHandset } from '../imei';
import { clean, mode, toNumber } from '../util';
import { exactIndex, makeCell, rowSignature } from './table';
import type { DatasetDraft } from './index';

// True and DTAC (same subpoena portal) deliver one workbook with an "Info"
// sheet plus one sheet per service. Unlike the AIS layout:
//  * the VOICE / IMS / SMS sheets also hold records generated by the OTHER
//    party's handset whenever that party is on the same network — each row's
//    owner is resolved from the IMSI first and the event role second;
//  * one call can appear in up to four rows: the caller's and the callee's
//    legs, each in IMS (VoLTE) and/or VOICE (circuit-switched). All rows of
//    one call are merged into one interaction.

/** Rows of one call share A/B and start within this window (answered calls match to the second). */
const SAME_CALL_MS = 3000;
/**
 * Unanswered attempts are time-stamped differently by the two cores: the
 * VOICE row is written up to ~15 s AFTER the IMS row of the same attempt.
 * An unanswered VOICE row that follows an unanswered IMS row of the same
 * pair within this window is therefore the same attempt.
 */
const SAME_ATTEMPT_MS = 20000;

type CommKind = 'VOICE' | 'IMS' | 'SMS';

function sheetKind(name: string): CommKind | 'DATA' | 'WIFI' | 'INFO' | undefined {
  const n = name.trim().toUpperCase();
  if (n === 'INFO') return 'INFO';
  if (/^(CS\s+)?VOICE(\s+SERVICE)?$/.test(n)) return 'VOICE';
  if (/^(IMS|VOLTE|VO-?LTE)(\s+SERVICE)?$/.test(n)) return 'IMS';
  if (/^SMS(\s+SERVICE)?$/.test(n)) return 'SMS';
  if (/^(DATA|GPRS|INTERNET)(\s+SERVICE)?$/.test(n)) return 'DATA';
  if (/^WI-?FI(\s+SERVICE)?$/.test(n)) return 'WIFI';
  return undefined;
}

export function looksLikeDtac(wb: RawWorkbook): boolean {
  const kinds = wb.sheets.map((s) => sheetKind(s.name)).filter((k) => k && k !== 'INFO');
  return kinds.length >= 2 || (kinds.length >= 1 && wb.sheets.some((s) => sheetKind(s.name) === 'INFO'));
}

interface InfoFields {
  msisdn?: string;
  period?: string;
}

function readInfo(sheet: RawSheet | undefined): InfoFields {
  const out: InfoFields = {};
  if (!sheet) return out;
  for (const row of sheet.rows) {
    const label = String(row[0] ?? '').trim().toLowerCase();
    const value = String(row[1] ?? '').trim();
    if (label.startsWith('search by')) {
      const m = /MSISDN\s*=\s*\+?(\d+)/i.exec(value);
      if (m) out.msisdn = m[1];
    } else if (label.startsWith('period of data')) {
      out.period = value;
    }
  }
  return out;
}

interface CommRec {
  kind: CommKind;
  /** Calls (VOICE + IMS voice) and SMS are merged separately. */
  domain: 'call' | 'sms';
  rowRef: string;
  ts: number;
  a: PhoneInfo;
  b: PhoneInfo;
  aRaw?: string;
  bRaw?: string;
  type: string;
  roleSide: 'A' | 'B';
  owner: 'target' | 'peer';
  obs: Observation;
  /**
   * Cell of an IMS row without an IMEI. Such rows are not written from the
   * handset's radio context: when they carry the target's IMSI their cell
   * lies away from the target (the far end of the call), so it is kept apart.
   */
  farCell?: Cell;
  duration?: number;
  answered: boolean;
  access?: string;
  dup: boolean;
}

function roleSideOf(kind: CommKind, type: string): 'A' | 'B' {
  const t = type.toUpperCase();
  if (kind === 'IMS') return t.startsWith('TERM') ? 'B' : 'A';
  if (kind === 'SMS') return t.includes('MT') ? 'B' : 'A';
  return t === 'MT' ? 'B' : 'A';
}

function emptyStat(name: string, rows: number): SheetStat {
  return { sheet: name, rows, used: 0, skippedNoTime: 0, peerOwned: 0, noLocation: 0, unknownTypes: {}, duplicates: 0 };
}

/**
 * Column lookup: exact header first (the layout has both "CELL ID" and
 * "CELL_ID"), then a spacing/underscore-insensitive fallback for variants.
 */
function columns(header: (string | null)[]): (name: string) => number {
  const exact = exactIndex(header);
  const loose = new Map<string, number>();
  header.forEach((h, i) => {
    const k = String(h ?? '').toUpperCase().replace(/[\s_-]+/g, '');
    if (!loose.has(k)) loose.set(k, i);
  });
  return (name) => {
    const i = exact(name);
    return i >= 0 ? i : (loose.get(name.toUpperCase().replace(/[\s_-]+/g, '')) ?? -1);
  };
}

function cellFrom(row: (string | null)[], col: (n: string) => number): Cell | undefined {
  const g = (n: string) => {
    const i = col(n);
    return i < 0 ? null : (row[i] ?? null);
  };
  return makeCell({
    lac: g('LAC ID'),
    ci: g('CELL ID'),
    cellName: g('CELL_ID'),
    site: g('SITE_NAME'),
    tumbol: g('TUMBON') ?? g('TUMBOL'),
    amphur: g('AMPHUR'),
    province: g('PROVINCE'),
    lat: g('LATITUDE'),
    lon: g('LONGITUDE'),
  });
}

interface SimTally {
  rows: number;
  withCell: number;
  /** DATA-sheet rows. */
  data: number;
  /** Communication rows where the SIM sits on the target's side of the event (MO with A = target, MT with B = target). */
  targetSide: number;
  peerSide: number;
  /** Numbers on the SIM's side of its events that are not the target. */
  numbers: Map<string, number>;
  /** Handsets (IMEI core) the SIM was used in. */
  imeis: Map<string, number>;
  firstTs: number;
  lastTs: number;
}

const finite = (ts: number) => (Number.isFinite(ts) ? ts : NaN);

function tallySim(sims: Map<string, SimTally>, imsi: string, ts: number, withCell: boolean, imei: string | null | undefined): SimTally {
  let t = sims.get(imsi);
  if (!t) {
    t = { rows: 0, withCell: 0, data: 0, targetSide: 0, peerSide: 0, numbers: new Map(), imeis: new Map(), firstTs: Infinity, lastTs: -Infinity };
    sims.set(imsi, t);
  }
  t.rows++;
  const core = imeiCore(imei);
  if (core) t.imeis.set(core, (t.imeis.get(core) ?? 0) + 1);
  if (withCell) t.withCell++;
  if (!Number.isNaN(ts)) {
    t.firstTs = Math.min(t.firstTs, ts);
    t.lastTs = Math.max(t.lastTs, ts);
  }
  return t;
}

/** Can record r join group g as another row of the same call/attempt? */
function belongsTo(g: CommRec[], r: CommRec): boolean {
  // One row per sheet and per handset: two such rows are two communications.
  if (g.some((m) => m.kind === r.kind && m.owner === r.owner)) return false;
  const dt = Math.abs(r.ts - g[0].ts);
  if (dt <= SAME_CALL_MS) return true;
  return (
    r.domain === 'call' &&
    r.kind === 'VOICE' &&
    dt <= SAME_ATTEMPT_MS &&
    !r.answered &&
    g.every((m) => !m.answered) &&
    g.some((m) => m.kind === 'IMS')
  );
}

/** Prefer a row that carries a position. */
function pickObs(rows: CommRec[]): Observation | undefined {
  if (!rows.length) return undefined;
  return (rows.find((r) => r.obs.cell) ?? rows[0]).obs;
}

export function parseDtacWorkbook(wb: RawWorkbook, zMode: ZMode, forcedTarget?: string, imsiOwners: ImsiOwners = {}): DatasetDraft {
  const bySheet = new Map<string, RawSheet>();
  for (const s of wb.sheets) {
    const k = sheetKind(s.name);
    if (k && !bySheet.has(k)) bySheet.set(k, s);
  }
  const info = readInfo(bySheet.get('INFO'));
  const data = bySheet.get('DATA');

  // ---- Target number --------------------------------------------------
  let target = forcedTarget ? normalizeNumber(forcedTarget).key : info.msisdn ? normalizeNumber(info.msisdn).key : '';
  if (!target && data && data.rows.length > 1) {
    const col = columns(data.rows[0]);
    target = mode(data.rows.slice(1), (r) => normalizeNumber(r[col('A NUMBER')]).key || undefined) ?? '';
  }

  // ---- Target IMSIs: the DATA sheet only ever holds the target's sessions.
  const targetImsis = new Set<string>();
  const sims = new Map<string, SimTally>();
  if (data && data.rows.length > 1) {
    const col = columns(data.rows[0]);
    for (const r of data.rows.slice(1)) {
      const imsi = clean(r[col('IMSI')]);
      if (!imsi) continue;
      targetImsis.add(imsi);
      tallySim(sims, imsi, parseWallClock(r[col('START TIME')], zMode), !!cellFrom(r, col), clean(r[col('IMEI')])).data++;
    }
  }

  const stats: SheetStat[] = [];
  const statOf = new Map<CommKind, SheetStat>();
  const comm: CommRec[] = [];
  const roleOwnedImsis: string[] = [];

  for (const kind of ['VOICE', 'IMS', 'SMS'] as CommKind[]) {
    const sheet = bySheet.get(kind);
    if (!sheet || sheet.rows.length === 0) continue;
    const col = columns(sheet.rows[0]);
    const g = (row: (string | null)[], n: string) => {
      const i = col(n);
      return i < 0 ? null : (row[i] ?? null);
    };
    const stat = emptyStat(sheet.name, sheet.rows.length - 1);
    statOf.set(kind, stat);
    const seen = new Set<string>();
    sheet.rows.slice(1).forEach((row, i) => {
      if (row.every((c) => c == null || String(c).trim() === '')) {
        stat.rows--;
        return;
      }
      const ts = parseWallClock(g(row, 'START TIME'), zMode);
      if (Number.isNaN(ts)) {
        stat.skippedNoTime++;
        return;
      }
      const sig = rowSignature(row);
      const dup = seen.has(sig);
      if (dup) stat.duplicates++;
      else seen.add(sig);
      const type = clean(g(row, 'EVENT TYPE')) ?? '';
      const aRaw = clean(g(row, 'A NUMBER'));
      const bRaw = clean(g(row, 'B NUMBER'));
      const a = normalizeNumber(aRaw, { restoreLeadingZero: false });
      const b = normalizeNumber(bRaw, { restoreLeadingZero: false });
      const roleSide = roleSideOf(kind, type);
      const obs: Observation = {};
      const imsi = clean(g(row, 'IMSI'));
      const imei = clean(g(row, 'IMEI'));
      if (imsi) obs.imsi = imsi;
      if (imei) obs.imei = imei;
      const cell = cellFrom(row, col);
      const farCell = kind === 'IMS' && !imei ? cell : undefined;
      if (cell && !farCell) obs.cell = cell;
      const sideKey = roleSide === 'A' ? a.key : b.key;
      if (imsi && sideKey === target) roleOwnedImsis.push(imsi);
      const media = clean(g(row, 'MEDIA TYPE'));
      const duration = toNumber(g(row, 'DURATION'));
      comm.push({
        kind,
        domain: kind === 'SMS' || (media && /sms|message/i.test(media)) ? 'sms' : 'call',
        rowRef: `${sheet.name}!${i + 2}`,
        ts,
        a,
        b,
        aRaw,
        bRaw,
        type,
        roleSide,
        owner: 'peer', // resolved below once the target IMSIs are known
        obs,
        ...(farCell ? { farCell } : {}),
        duration,
        answered: duration !== undefined && duration > 0,
        access: clean(g(row, 'ACCESSNETWORKINFO')),
        dup,
      });
      stat.used++;
    });
    stats.push(stat);
  }

  // ---- Whose handset wrote each row. The IMSI decides: a row from another
  // SIM is a same-network peer's leg, and its cell is the peer's position.
  for (const r of comm) {
    if (!r.obs.imsi) continue;
    const t = tallySim(sims, r.obs.imsi, r.ts, !!(r.obs.cell ?? r.farCell), r.obs.imei);
    // A forwarding record is written by the network, not by a handset on either side.
    if (r.kind === 'VOICE' && r.type.toUpperCase() === 'CF') continue;
    const sideKey = r.roleSide === 'A' ? r.a.key : r.b.key;
    if (sideKey === target) t.targetSide++;
    else {
      t.peerSide++;
      const other = sideKey || (r.a.key === target ? r.b.key : r.a.key);
      if (other) t.numbers.set(other, (t.numbers.get(other) ?? 0) + 1);
    }
  }
  const basis = new Map<string, ImsiCheck['basis']>([...targetImsis].map((i) => [i, 'data']));
  // Without DATA rows, the SIM most often on the target's side of the events.
  if (targetImsis.size === 0) {
    const top = mode(roleOwnedImsis, (x) => x);
    if (top) {
      targetImsis.add(top);
      basis.set(top, 'main');
    }
  }
  // The target is taken to have one SIM. Another SIM is the target's only on
  // strong evidence of a SIM change: it sits on the target's side of its
  // events, is never in use while the target's SIMs are (one number, one SIM
  // at a time; a peer's SIM is in use alongside the target's), and it was
  // used in a handset the target's SIM was also used in. Without that shared
  // handset it stays a peer's, flagged for review: its IMEI may well be the
  // peer's phone.
  const candidates = [...sims].filter(([imsi, t]) => !targetImsis.has(imsi) && t.targetSide >= 2 && t.targetSide > t.peerSide);
  for (const [imsi, t] of candidates.sort((x, y) => y[1].targetSide - x[1].targetSide)) {
    const known = [...targetImsis].map((o) => sims.get(o)).filter((u): u is SimTally => !!u);
    if (known.some((u) => t.firstTs <= u.lastTs && u.firstTs <= t.lastTs)) continue;
    const handsets = known.flatMap((u) => [...u.imeis.keys()]);
    const sameHandset = [...t.imeis.keys()].some((e) => handsets.some((h) => h === e || likelySameHandset(h, e)));
    if (sameHandset) {
      targetImsis.add(imsi);
      basis.set(imsi, 'sim-change');
    } else basis.set(imsi, 'review');
  }

  // The investigator's word over the rules, for SIMs outside the DATA sheet
  // (that sheet holds only the target's sessions by subpoena).
  const autoTarget = new Set(targetImsis);
  let manual = 0;
  for (const [imsi, owner] of Object.entries(imsiOwners)) {
    const t = sims.get(imsi);
    if (!t || t.data > 0 || (owner === 'target') === autoTarget.has(imsi)) continue;
    if (owner === 'target') targetImsis.add(imsi);
    else targetImsis.delete(imsi);
    basis.set(imsi, 'manual');
    manual++;
  }

  let farCells = 0;
  const byRole = { target: { rows: 0, withCell: 0, firstTs: Infinity, lastTs: -Infinity }, peer: { rows: 0, withCell: 0, firstTs: Infinity, lastTs: -Infinity } };
  for (const r of comm) {
    const sideKey = r.roleSide === 'A' ? r.a.key : r.b.key;
    r.owner = r.obs.imsi ? (targetImsis.has(r.obs.imsi) ? 'target' : 'peer') : sideKey === target ? 'target' : 'peer';
    const st = statOf.get(r.kind)!;
    // A peer's own row: whatever its cell, it is the peer's position.
    if (r.owner === 'peer' && r.farCell) {
      r.obs.cell = r.farCell;
      delete r.farCell;
    }
    if (r.farCell) farCells++;
    if (!r.obs.cell) st.noLocation++;
    if (r.owner === 'peer') st.peerOwned++;
    if (!r.obs.imsi) {
      const b = byRole[r.owner];
      b.rows++;
      if (r.obs.cell) b.withCell++;
      b.firstTs = Math.min(b.firstTs, r.ts);
      b.lastTs = Math.max(b.lastTs, r.ts);
    }
  }
  const imsiCheck: ImsiCheck[] = [...sims]
    .map(([imsi, t]): ImsiCheck => {
      const mine = targetImsis.has(imsi);
      const number = mine ? target : [...t.numbers].sort((x, y) => y[1] - x[1])[0]?.[0];
      return {
        imsi,
        owner: mine ? 'target' : 'peer',
        ...(number ? { number } : {}),
        basis: basis.get(imsi) === 'manual' ? 'manual' : mine ? (basis.get(imsi) ?? 'other') : basis.get(imsi) === 'review' ? 'review' : 'other',
        auto: autoTarget.has(imsi) ? 'target' : 'peer',
        inData: t.data > 0,
        imeis: [...t.imeis].sort((x, y) => y[1] - x[1]).map(([e]) => e),
        rows: t.rows,
        withCell: t.withCell,
        firstTs: finite(t.firstTs),
        lastTs: finite(t.lastTs),
      };
    })
    .sort((x, y) => (x.owner === y.owner ? y.rows - x.rows : x.owner === 'target' ? -1 : 1));
  for (const owner of ['target', 'peer'] as const) {
    const b = byRole[owner];
    if (b.rows) imsiCheck.push({ imsi: '', owner, ...(owner === 'target' && target ? { number: target } : {}), basis: 'role', auto: owner, inData: false, imeis: [], rows: b.rows, withCell: b.withCell, firstTs: finite(b.firstTs), lastTs: finite(b.lastTs) });
  }

  // ---- Merge every row of the same communication, across VOICE and IMS.
  comm.sort((x, y) => x.ts - y.ts);
  const groups: CommRec[][] = [];
  const open = new Map<string, CommRec[][]>();
  for (const r of comm) {
    const key = `${r.domain}|${r.a.key}|${r.b.key}`;
    const list = (open.get(key) ?? []).filter((g) => r.ts - g[0].ts <= SAME_ATTEMPT_MS);
    const hit = list.find((g) => belongsTo(g, r));
    if (hit) hit.push(r);
    else {
      const g = [r];
      groups.push(g);
      list.push(g);
    }
    open.set(key, list);
  }

  const interactions: Interaction[] = [];
  let unanswered = 0;
  let notInvolving = 0;
  let mergedRows = 0;
  let crossSheet = 0;
  let crossSheetAttempts = 0;
  for (const g of groups) {
    const mine = g.filter((r) => r.owner === 'target');
    const theirs = g.filter((r) => r.owner === 'peer');
    const first = g[0];
    const kinds = new Set(g.map((r) => r.kind));
    mergedRows += g.length - 1;
    const isFwd = g.every((r) => r.kind === 'VOICE' && r.type.toUpperCase() === 'CF');
    let direction: Interaction['direction'];
    let peerInfo: PhoneInfo;
    let peerRaw: string | undefined;
    if (first.a.key === target) {
      direction = 'out';
      peerInfo = first.b;
      peerRaw = first.bRaw;
    } else if (first.b.key === target) {
      direction = 'in';
      peerInfo = first.a;
      peerRaw = first.aRaw;
    } else {
      direction = 'na';
      peerInfo = first.b;
      peerRaw = first.bRaw;
      notInvolving++;
    }
    if (isFwd) direction = 'fwd';
    const service = first.domain === 'sms' ? 'sms' : 'call';
    const durations = g.map((r) => r.duration).filter((d): d is number => d !== undefined);
    const duration = durations.length ? Math.max(...durations) : undefined;
    const source: SourceKind = kinds.size > 1 ? 'VOICE+IMS' : first.kind;
    if (kinds.has('VOICE') && kinds.has('IMS')) {
      crossSheet++;
      if (g.every((r) => !r.answered)) crossSheetAttempts++;
    }
    const it: Interaction = {
      id: interactions.length,
      ts: Math.min(...g.map((r) => r.ts)),
      service,
      direction,
      peerKind: peerInfo.kind,
      rawType: [...new Set(g.map((r) => r.type))].join('+'),
      source,
      rowRefs: g.map((r) => r.rowRef),
    };
    if (peerInfo.key) {
      it.peer = peerInfo.key;
      if (peerRaw) it.peerRaw = peerRaw;
      if (peerInfo.country) it.peerCountry = peerInfo.country;
    }
    if (duration !== undefined) it.durationSec = duration;
    if (service === 'call' && !isFwd) {
      it.answered = g.some((r) => r.answered);
      if (!it.answered) unanswered++;
      if (duration) it.endTs = it.ts + duration * 1000;
    }
    const tObs = pickObs(mine);
    const pObs = pickObs(theirs);
    if (tObs) it.targetObs = tObs;
    if (pObs) it.peerObs = pObs;
    // The far end of the call as seen in the target's IMS rows without an IMEI.
    const far = mine.find((r) => r.farCell)?.farCell;
    if (far && !it.peerObs?.cell) {
      it.peerObs = { ...it.peerObs, cell: far };
      it.peerCellInferred = true;
    }
    if (g.every((r) => r.dup)) it.dupOfPrev = true;
    const access = g.find((r) => r.access)?.access;
    if (access) it.extra = { 'เครือข่าย': access };
    interactions.push(it);
  }

  // ---- DATA sessions (always the target's own handset).
  let dataPlmn: string | undefined;
  if (data && data.rows.length > 0) {
    const col = columns(data.rows[0]);
    const g = (row: (string | null)[], n: string) => {
      const i = col(n);
      return i < 0 ? null : (row[i] ?? null);
    };
    const stat = emptyStat(data.name, data.rows.length - 1);
    const seen = new Set<string>();
    dataPlmn = mode(data.rows.slice(1), (r) => clean(g(r, 'PUBLIC LAND MOBILE NETWORK')) ?? clean(g(r, 'PLMN')));
    data.rows.slice(1).forEach((row, i) => {
      if (row.every((c) => c == null || String(c).trim() === '')) {
        stat.rows--;
        return;
      }
      const ts = parseWallClock(g(row, 'START TIME'), zMode);
      if (Number.isNaN(ts)) {
        stat.skippedNoTime++;
        return;
      }
      const sig = rowSignature(row);
      const dup = seen.has(sig);
      if (dup) stat.duplicates++;
      else seen.add(sig);
      const obs: Observation = {};
      const imsi = clean(g(row, 'IMSI'));
      const imei = clean(g(row, 'IMEI'));
      if (imsi) obs.imsi = imsi;
      if (imei) obs.imei = imei;
      const cell = cellFrom(row, col);
      if (cell) obs.cell = cell;
      else stat.noLocation++;
      const it: Interaction = {
        id: interactions.length,
        ts,
        service: 'data',
        direction: 'na',
        peerKind: 'none',
        rawType: 'DATA',
        source: 'DATA',
        rowRefs: [`${data.name}!${i + 2}`],
        targetObs: obs,
      };
      const dur = toNumber(g(row, 'DURATION'));
      if (dur !== undefined) {
        it.durationSec = dur;
        it.endTs = ts + dur * 1000;
      }
      const vol = toNumber(g(row, 'VOLUME'));
      if (vol !== undefined) it.bytes = vol;
      const ip = clean(g(row, 'IP ADDRESS'));
      if (ip) it.ip = ip;
      if (dup) it.dupOfPrev = true;
      interactions.push(it);
      stat.used++;
    });
    stats.push(stat);
  }

  // ---- Wi-Fi calling sessions (RADIUS accounting: start + stop rows).
  const wifi = bySheet.get('WIFI');
  if (wifi && wifi.rows.length > 0) {
    const col = columns(wifi.rows[0]);
    const g = (row: (string | null)[], n: string) => {
      const i = col(n);
      return i < 0 ? null : (row[i] ?? null);
    };
    const stat = emptyStat(wifi.name, wifi.rows.length - 1);
    const sessions = new Map<string, { row: (string | null)[]; rowNos: number[] }>();
    wifi.rows.slice(1).forEach((row, i) => {
      if (row.every((c) => c == null || String(c).trim() === '')) {
        stat.rows--;
        return;
      }
      const id = clean(g(row, 'ACCT-SESSION-ID')) ?? `row${i}`;
      const cur = sessions.get(id);
      const isStop = clean(g(row, 'ACC-STATUS-TYPE')) === '2';
      if (!cur) sessions.set(id, { row, rowNos: [i + 2] });
      else {
        cur.rowNos.push(i + 2);
        if (isStop) cur.row = row.map((c, k) => c ?? cur.row[k] ?? null);
        else cur.row = cur.row.map((c, k) => c ?? row[k] ?? null);
      }
    });
    for (const { row, rowNos } of sessions.values()) {
      const ts = parseWallClock(g(row, 'ACCT-START-TIME'), zMode);
      if (Number.isNaN(ts)) {
        stat.skippedNoTime += rowNos.length;
        continue;
      }
      const obs: Observation = {};
      const imsi = clean(g(row, 'IMSI'));
      const imei = clean(g(row, 'IMEI'));
      if (imsi) obs.imsi = imsi;
      if (imei) obs.imei = imei;
      const it: Interaction = {
        id: interactions.length,
        ts,
        service: 'wifi',
        direction: 'na',
        peerKind: 'none',
        rawType: 'WIFI',
        source: 'WIFI',
        rowRefs: rowNos.map((n) => `${wifi.name}!${n}`),
        targetObs: obs,
      };
      const dur = toNumber(g(row, 'ACCT-SESSION-TIME'));
      if (dur !== undefined) it.durationSec = dur;
      const end = parseWallClock(g(row, 'ACCT-END-TIME'), zMode);
      if (!Number.isNaN(end) && end >= ts) it.endTs = end;
      const octets = (toNumber(g(row, 'ACCT-INPUT-OCTETS')) ?? 0) + (toNumber(g(row, 'ACCT-OUTPUT-OCTETS')) ?? 0);
      const giga = (toNumber(g(row, 'ACCT-INPUT-GIGAWARDS')) ?? 0) + (toNumber(g(row, 'ACCT-OUTPUT-GIGAWORD')) ?? 0);
      if (octets || giga) it.bytes = octets + giga * 2 ** 32;
      const ip = clean(g(row, 'FRAMED-IP-ADDRESS'));
      if (ip) it.ip = ip;
      const extra: Record<string, string> = {};
      const loc = clean(g(row, 'LOCATION'));
      if (loc) extra['จุดให้บริการ Wi-Fi'] = loc;
      const ssid = clean(g(row, 'CALLED-STATION-ID'));
      if (ssid) extra['SSID'] = ssid;
      if (Object.keys(extra).length) it.extra = extra;
      interactions.push(it);
      stat.used += rowNos.length;
    }
    stats.push(stat);
  }

  interactions.sort((x, y) => x.ts - y.ts);
  interactions.forEach((it, i) => (it.id = i));

  const hasCoordinates = interactions.some((x) => x.targetObs?.cell?.lat !== undefined);
  const peerOwned = stats.reduce((n, s) => n + s.peerOwned, 0);
  const commRows = comm.length;
  const notes: string[] = [];
  if (peerOwned > 0) {
    const others = imsiCheck.filter((c) => c.owner === 'peer' && c.imsi).length;
    notes.push(
      `ไฟล์มีบันทึกที่มาจากเครื่องของคู่สาย (ลูกค้าเครือข่ายเดียวกัน) ${peerOwned.toLocaleString('th-TH')} แถว` +
        (others ? ` จาก IMSI ที่ไม่ใช่ของเป้าหมาย ${others.toLocaleString('th-TH')} ค่า` : '') +
        ` ระบบแยกตำแหน่งของคู่สายออกจากตำแหน่งของเป้าหมายโดยดูจาก IMSI ตำแหน่งเหล่านี้จึงไม่ถูกนับเป็นตำแหน่งของเป้าหมาย (ดูตาราง "ตรวจเจ้าของพิกัดจาก IMSI")`,
    );
  }
  if (manual > 0) {
    notes.push(`ผู้ใช้กำหนดเจ้าของ IMSI เอง ${manual} ค่า (แทนผลที่ระบบตัดสิน) พิกัดและเครื่องของซิมเหล่านี้นับตามที่กำหนด`);
  }
  if (farCells > 0) {
    notes.push(
      `แถว IMS ที่ใช้ IMSI ของเป้าหมายแต่ไม่มี IMEI ${farCells.toLocaleString('th-TH')} แถวมีพิกัด: แถวเหล่านี้ไม่ได้บันทึกจากเครื่องของเป้าหมาย พิกัดมักอยู่คนละพื้นที่กับเป้าหมาย (เช่น สายเดียวกันในชีต VOICE ที่มี IMEI อยู่คนละจังหวัด) และน่าจะเป็นตำแหน่งของฝั่งคู่สาย ระบบจึงไม่นับเป็นตำแหน่งของเป้าหมาย และแสดงบนแผนที่เป็นสี่เหลี่ยม`,
    );
  }
  const review = imsiCheck.filter((c) => c.basis === 'review').length;
  if (review > 0) {
    notes.push(
      `พบ IMSI อื่น ${review} ค่าที่อยู่ฝั่งเป้าหมายและใช้ไม่ทับช่วงเวลากับซิมของเป้าหมาย แต่ใช้กับเครื่อง (IMEI) ที่ซิมของเป้าหมายไม่เคยใช้ ระบบถือว่าเป็นของคู่สายและไม่นับพิกัดเป็นของเป้าหมาย ควรตรวจสอบว่าเป้าหมายเปลี่ยนทั้งซิมและเครื่องหรือไม่ (ดูตาราง "ตรวจเจ้าของพิกัดจาก IMSI")`,
    );
  }
  const changed = imsiCheck.filter((c) => c.basis === 'sim-change').length;
  if (changed > 0) {
    notes.push(`เป้าหมายใช้ซิมมากกว่า 1 ใบในช่วงข้อมูล (พบ IMSI ของเป้าหมาย ${targetImsis.size} ค่า ใช้ต่างช่วงเวลากันในเครื่องเดียวกัน) ระบบนับพิกัดจากทุกซิมของเป้าหมายเป็นตำแหน่งของเป้าหมาย`);
  }
  if (mergedRows > 0) {
    notes.push(
      `การติดต่อครั้งเดียวกันที่ถูกบันทึกหลายแถว (ฝั่งต้นทาง/ปลายทาง และ/หรือทั้งในชีต VOICE และ IMS) ถูกรวมเป็นรายการเดียว: ${commRows.toLocaleString('th-TH')} แถว เหลือ ${groups.length.toLocaleString('th-TH')} รายการ`,
    );
  }
  if (crossSheet > 0) {
    notes.push(
      `พบการโทรที่ถูกบันทึกซ้ำทั้งในชีต VOICE และ IMS ${crossSheet.toLocaleString('th-TH')} ครั้ง ซึ่งนับเป็นครั้งเดียวแล้ว` +
        (crossSheetAttempts ? ` (ในจำนวนนี้มี ${crossSheetAttempts} ครั้งที่เป็นการโทรไม่สำเร็จ ซึ่งสองชีตบันทึกเวลาห่างกันไม่เกิน ${SAME_ATTEMPT_MS / 1000} วินาที)` : ''),
    );
  }
  if (comm.some((r) => r.kind === 'SMS') && comm.filter((r) => r.kind === 'SMS').every((r) => r.roleSide === 'B')) {
    notes.push('ชีต SMS มีเฉพาะรายการ SMS-MT (ฝั่งผู้รับ) ดังนั้น SMS ที่เป้าหมายส่งออกจะปรากฏเฉพาะเมื่อผู้รับเป็นลูกค้าเครือข่ายเดียวกันเท่านั้น');
  }
  if (unanswered > 0) {
    notes.push(`มีการโทรที่ไม่สำเร็จหรือไม่มีระยะเวลาสนทนา ${unanswered.toLocaleString('th-TH')} ครั้ง (นับแยกจากสายที่สนทนาสำเร็จ)`);
  }
  if (notInvolving > 0) notes.push(`มี ${notInvolving} รายการที่ไม่ปรากฏหมายเลขเป้าหมายทั้งฝั่ง A และ B`);
  if (!target) notes.push('ไม่พบหมายเลขเป้าหมายในไฟล์ (Info/DATA) กรุณาระบุเอง');

  // Brand from the network code of the data sessions, else from the SIM's IMSI prefix.
  const imsiPlmn = [...targetImsis][0]?.slice(0, 5);
  const operator = operatorFromPlmn(dataPlmn) ?? operatorFromPlmn(imsiPlmn) ?? 'True/DTAC';

  return {
    fileName: wb.fileName,
    target,
    interactions,
    meta: {
      format: 'dtac',
      formatLabel: 'True/DTAC หลายชีต (VOICE/IMS/SMS/DATA/WIFI)',
      operator,
      declaredPeriod: info.period,
      sheets: stats,
      targetImsis: [...targetImsis],
      imsiCheck,
      notes,
      zMode,
      hasCoordinates,
    },
  };
}
